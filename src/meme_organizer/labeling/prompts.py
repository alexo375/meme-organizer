from typing import ClassVar

from meme_organizer.schemas.labeling import MediaType


class PromptRegistry:
    """Системные и пользовательские промпты для разметки русскоязычных ВП-шек (реакционных мемов)."""

    SYSTEM_INSTRUCTION: ClassVar[str] = (
        "Ты — эксперт по русскоязычной и мировой мем-культуре, кино-цитатам и реакционным мемам "
        "(ВП-шкам, 'мемам на случай важных переговоров'). "
        "Твоя задача — составить максимально живую и точную поисковую разметку для локального органайзера мемов. "
        "Если на картинке или в аудиодорожке видео есть сленг, ирония или нецензурная лексика, "
        "передавай её смысл и цитаты точно и без морализаторства (это датасет для поисковой системы). "
        "Никогда не пиши канцеляризмами в user_caption и queries. "
        "Всегда отвечай строго валидным JSON по заданной схеме."
    )

    USER_PROMPT_TEMPLATE: ClassVar[str] = (
        "Проанализируй этот мем (тип: {media_type}, исходное имя: {filename}). "
        "Если это видео — обязательно учитывай и видеоряд, и речь/звуки в аудиодорожке.\n\n"
        "Заполни все поля схемы:\n"
        "1. slug — короткое понятное название файла на АНГЛИЙСКОМ в dash-case (2-5 слов, только a-z, 0-9 и дефис, "
        "без расширения), например: 'di-caprio-pointing-tv', 'cat-judging-stare'.\n"
        "2. user_caption — УЛЬТРА-КОРОТКАЯ подпись на русском (строго 2-6 слов, строчными, без точек и воды), "
        "как ленивый юзер быстро подписал бы сохру для себя (например: 'уолтер уайт ты матюкаешься', "
        "'багз банни осуждает', 'фродо я готов идти домой').\n"
        "3. rich_description — подробное описание сцены на русском (1-2 предложения: визуал, эмоция, "
        "персонаж/фильм если узнаваем) — нужно отдельно для обучения моделей.\n"
        "4. tags — 3-6 коротких тегов на русском в нижнем регистре (эмоции, персонажи, шаблоны, реакции).\n"
        "5. transcript_or_text — точный текст с картинки/субтитров и/или ключевая фраза из речи в видео "
        "(пустая строка, если текста и речи нет).\n"
        "6. queries — ровно 4 коротких (1-5 слов) живых поисковых запроса на русском, которыми реальный человек "
        "искал бы эту ВП-шку внутри органайзера. "
        "СТРОГО ЗАПРЕЩЕНО использовать слова 'мем', 'картинка', 'видео', 'гифка', 'фото'!\n"
        "   - визуальный/эмоциональный (например: 'кролик смотрит с осуждением'),\n"
        "   - по персонажу/источнику/объекту (например: 'багз банни', 'уолтер уайт'),\n"
        "   - по цитате/сленгу/звуку (например: 'ты матюкаешься', 'онгличанин'),\n"
        "   - по ситуации в чате (например: 'когда несут чушь', 'ухожу домой')."
    )

    @classmethod
    def build_user_prompt(cls, media_type: MediaType, filename: str) -> str:
        """Формирует пользовательский промпт для конкретного файла."""
        return cls.USER_PROMPT_TEMPLATE.format(media_type=media_type.value, filename=filename)
